-- 08_write_path.sql: the clinical write path (production plan, Phase 1). Run as MED_ADMIN. Idempotent.
--
-- Design (ADR-014, spike scripts/spikes/s_e_write_path.py): only owner's-rights procedures in INTAKE write CLINICAL.
-- They are owned by MED_CLINICAL_WRITER and called by the API's service role (MED_API) with the verified actor's user
-- id. Inside Snowflake each procedure re-checks that the actor is an active doctor entitled to the patient, so a
-- caller who skips the API check is still refused. Doctor and assistant roles (and every U_ role) stay read-only.
-- INVOKER_ROLE() cannot be used for this: inside an owner's-rights procedure it returns the owner (spike S-E).
USE ROLE MED_PROVISIONER;
CREATE ROLE IF NOT EXISTS MED_CLINICAL_WRITER
  COMMENT = 'Owns the INTAKE procedures, the only code that writes CLINICAL. Never granted to MED_API, MED_DOCTOR or a U_ role.';
GRANT ROLE MED_CLINICAL_WRITER TO USER {{ADMIN_USER}};

USE ROLE MED_ADMIN;
USE WAREHOUSE {{WH}};
USE DATABASE {{DB}};

CREATE SCHEMA IF NOT EXISTS INTAKE COMMENT = 'Intake procedures: the write path into CLINICAL, and request bookkeeping.';

