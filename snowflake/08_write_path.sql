-- Archive, version and provenance columns on every table the write path touches ------------------------------
-- IS_ARCHIVED hides a row from every screen and read model; nothing is ever deleted at run time.
EXECUTE IMMEDIATE $$
DECLARE
  tables ARRAY DEFAULT ARRAY_CONSTRUCT('PATIENT', 'ENCOUNTER', 'DIAGNOSIS', 'MEDICATION', 'LAB_RESULT', 'ALLERGY', 'CLINICAL_NOTE');
  cols ARRAY DEFAULT ARRAY_CONSTRUCT(
    OBJECT_CONSTRUCT('n', 'IS_ARCHIVED', 'd', 'BOOLEAN NOT NULL DEFAULT FALSE'),
    OBJECT_CONSTRUCT('n', 'ARCHIVED_AT', 'd', 'TIMESTAMP_NTZ'),
    OBJECT_CONSTRUCT('n', 'ARCHIVED_BY', 'd', 'VARCHAR'),
    OBJECT_CONSTRUCT('n', 'VERSION', 'd', 'NUMBER NOT NULL DEFAULT 1'),
    OBJECT_CONSTRUCT('n', 'UPDATED_AT', 'd', 'TIMESTAMP_NTZ'),
    OBJECT_CONSTRUCT('n', 'UPDATED_BY', 'd', 'VARCHAR'),
    OBJECT_CONSTRUCT('n', 'ENTERED_BY', 'd', 'VARCHAR'),
    OBJECT_CONSTRUCT('n', 'ENTRY_SOURCE', 'd', 'VARCHAR'));
  t VARCHAR;
  cname VARCHAR;
  cdef VARCHAR;
  existing ARRAY;
  added NUMBER DEFAULT 0;
BEGIN
  FOR i IN 0 TO ARRAY_SIZE(tables) - 1 DO
    t := tables[i]::VARCHAR;
    SELECT ARRAY_AGG(COLUMN_NAME) INTO :existing FROM {{DB}}.INFORMATION_SCHEMA.COLUMNS
      WHERE TABLE_SCHEMA = 'CLINICAL' AND TABLE_NAME = :t;
    FOR j IN 0 TO ARRAY_SIZE(cols) - 1 DO
      cname := cols[j]:n::VARCHAR;
      cdef := cols[j]:d::VARCHAR;
      IF (NOT ARRAY_CONTAINS(:cname::VARIANT, :existing)) THEN
        EXECUTE IMMEDIATE 'ALTER TABLE {{DB}}.CLINICAL.' || t || ' ADD COLUMN ' || cname || ' ' || cdef;
        added := added + 1;
      END IF;
    END FOR;
  END FOR;
  RETURN 'columns added: ' || added;
END;
$$;

-- Insert-only history of every write: who changed what, before and after ------------------------------------
CREATE TABLE IF NOT EXISTS CLINICAL.RECORD_HISTORY (
  HISTORY_ID VARCHAR NOT NULL,
  PATIENT_ID VARCHAR NOT NULL,
  ENTITY VARCHAR NOT NULL COMMENT 'PATIENT, DIAGNOSIS, MEDICATION, ALLERGY, LAB_RESULT, CLINICAL_NOTE or ENCOUNTER.',
  RECORD_ID VARCHAR NOT NULL,
  OP VARCHAR NOT NULL COMMENT 'CREATE, UPDATE, ARCHIVE or RESTORE.',
  BEFORE_JSON VARIANT,
  AFTER_JSON VARIANT,
  ACTOR_ID VARCHAR NOT NULL,
  REASON VARCHAR,
  ENTRY_SOURCE VARCHAR COMMENT 'MANUAL, or REPORT:<report id> once Phase 2 approvals write here.',
  AT TIMESTAMP_NTZ NOT NULL,
  PRIMARY KEY (HISTORY_ID)
) COMMENT = 'Append-only. One row per create, edit, archive or restore. Covered by the patient row access policy.';

-- Replays of a request that carried the same Idempotency-Key return the first result ---------------------------
CREATE TABLE IF NOT EXISTS INTAKE.REQUEST_LOG (
  REQUEST_KEY VARCHAR NOT NULL,
  ACTOR_ID VARCHAR NOT NULL,
  RESULT VARIANT,
  AT TIMESTAMP_NTZ NOT NULL,
  PRIMARY KEY (REQUEST_KEY, ACTOR_ID)
) COMMENT = 'Idempotency bookkeeping for the write path. No patient data. Service-side only.';

-- Read-model refreshes owed after a write. The API's background worker rebuilds each patient and marks the rows done;
-- a sweeper retries anything left over, so a restart never loses a refresh.
CREATE TABLE IF NOT EXISTS INTAKE.REFRESH_QUEUE (
  PATIENT_ID VARCHAR NOT NULL,
  ENQUEUED_AT TIMESTAMP_NTZ NOT NULL,
  DONE_AT TIMESTAMP_NTZ,
  ATTEMPTS NUMBER NOT NULL DEFAULT 0
) COMMENT = 'Outbox for read-model refreshes. Holds patient ids only. Service-side only.';

